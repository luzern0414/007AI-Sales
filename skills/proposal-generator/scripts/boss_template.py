d.table("方案要点", ["要点", "内容"], [
    ["怎么赋能", "① 感知：<设备与数据>\n② 汇聚：<数据底座>\n③ 赋能：<AI 嵌入哪些场景>"],
    ["AI 能做到", "① <能力与程度>\n② <能力与程度>\n③ <能力与程度>"],
    ["人来把关", "数字由程序计算，AI 只负责理解问题和起草文字，所有结论由业务人员确认后生效"],
    ["对比传统", "① <环节>：从“<旧>”到“<新>”\n② <环节>：从“<旧>”到“<新>”"],
    ["核心创新", "① <创新>：<一句话>\n② <创新>：<一句话>"],
], [2.6, 13.4])
