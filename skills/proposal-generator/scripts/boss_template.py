d.toc()


def scene(title, intro, who, before, system, ai, change, fig=None, caption=None):
    """应用场景统一写法：一段场景描述（像讲故事：谁、在什么时候、怎么用）+ 五行说明表。"""
    d.h2(title)
    d.p(intro)
    if fig:
        d.image(FIG / fig, 15.5, caption)
    name = title.split("：", 1)[-1].split("——")[0]
    d.table(f"{name}场景说明", ["项目", "说明"], [
        ["谁在用", who], ["以前怎么做", before], ["系统能做什么", system], ["AI 能做什么", ai], ["带来的变化", change],
    ], KV)


# 总述（不编号，执行摘要）———— 一句话概括 + “方案要点”表（分点分级，不写成大段文字）+ 全景图 + 一行全文脉络
d.h1("总述：AI 赋能<园区/项目>")
