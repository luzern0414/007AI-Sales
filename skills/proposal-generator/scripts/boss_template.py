if "--out" in sys.argv:
    DOC_DIR = Path(sys.argv[sys.argv.index("--out") + 1])
FIG = ROOT / "docs" / "素材"

ORG = "<甲方项目名称>"
TOPIC = "<方案主题，如“商业运营智能化”>"
TITLE = f"{TOPIC}建设方案（汇报版）"
