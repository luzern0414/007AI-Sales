d.h1("九、交付与验收")
d.h2("9.1 交付清单")
d.table("交付清单", ["类别", "交付物", "说明"], [("__group__", "硬件"), ["<>", "<>", "<>"],
                                               ("__group__", "软件"), ["<>", "<>", "<>"],
                                               ("__group__", "文档"), ["<>", "<>", "<>"],
                                               ("__group__", "服务"), ["<>", "<>", "<>"]], [3.4, 8.4, 4.2])
