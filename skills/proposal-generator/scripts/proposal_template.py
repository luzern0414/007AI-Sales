d.h1("五、AI 功能")
d.h2("5.1 使用原则")
d.p("AI 在本系统中只做辅助：程序负责计算数字，AI 负责理解问题和起草文字，最终由业务人员确认。")
d.image(FIG / "AI使用原则.png", 15.5, "AI 使用原则")
d.h2("5.2 功能一览")
d.table("AI 功能一览", ["功能", "主要使用人", "实现方式", "人工把关"], [["<>", "<>", "<>", "<>"]], [3.2, 3.0, 5.2, 4.6])
d.mute = BOSS  # —— 汇报版不含各功能说明 ——
