d.table("网络与供电配套", ["项目", "要求", "说明"], [["供电", "<>", "<>"], ["网络", "<>", "<>"]], [2.6, 5.4, 8.0])
d.h2("3.<n> 设备运维")
d.table("设备运维", ["项目", "做法"], [["在线监测", "<>"], ["故障维修", "<>"], ["质保期限", "<>"]], [2.6, 13.4])

# ================================================================ 四、数据与平台
d.h1("四、数据与平台")
d.h2("4.1 数据来源与汇聚")
d.image(FIG / "数据来源与用途.png", 15.5, "数据来源与用途")
d.table("数据来源与质量检查", ["数据", "来源", "更新频率", "自动检查"], [["<>", "<>", "<>", "<>"]], [2.4, 5.0, 3.2, 5.4])
d.h2("4.2 统一指标库")
