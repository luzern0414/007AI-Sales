"""方案正文脚本模板：复制到项目 scripts/docs/build_proposal.py，按“项目信息卡”填写内容。

用法：
  python build_proposal.py            → 完整版《××实施方案》（讨论稿，供甲方业务人员审核）
  python build_proposal.py --boss     → 汇报版《××建设方案（汇报版）》（给领导看，去掉实施细节）
两个版本由同一份正文生成：在要从汇报版删除的段落前后设置 d.mute = BOSS / d.mute = False。

章节结构、每节写什么、用什么表和图，见 references/02_文档结构.md。
所有 <尖括号> 处都要替换成项目真实内容；查不到的数字写“待确认”，不要编造。
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))  # 复制到项目后，改为 docx_kit.py 所在目录
from docx_kit import Doc

BOSS = "--boss" in sys.argv
ROOT = Path(__file__).resolve().parents[2]          # 项目根目录（scripts/docs/ 的上两级）
DOC_DIR = ROOT / "docs" / "01-商务与需求" / "方案文件"
if "--out" in sys.argv:                              # 可选：--out <正文输出目录>，图片仍从项目 docs/素材 读取
    DOC_DIR = Path(sys.argv[sys.argv.index("--out") + 1])
FIG = ROOT / "docs" / "素材"

# ---------------------------------------------------------------- 封面信息
ORG = "<甲方项目名称>"                                 # 封面第一行，如“深圳湾创新科技中心”
TOPIC = "<方案主题>"                                   # 如“商业运营智能化”
TAGLINE = "<关键词1 · 关键词2 · 关键词3 · 关键词4>"      # 4–6 个关键词
DATE = "<yyyy 年 m 月>"
if BOSS:
    TITLE, LINES, VER = f"{TOPIC}建设方案（汇报版）", [TOPIC, "建设方案"], "版本：V1.0（汇报版）"
else:
    TITLE, LINES, VER = f"{TOPIC}实施方案", [TOPIC, "实施方案"], "版本：V1.0（讨论稿）"
OUT = DOC_DIR / f"{TITLE}.docx"
OUT.parent.mkdir(parents=True, exist_ok=True)
KV = [2.6, 13.4]                                      # “项目—说明”两列表列宽（cm），合计必须 16

d = Doc(f"{ORG} · {TITLE}")
d.cover(ORG, LINES, TAGLINE, [VER, f"日期：{DATE}"])
d.toc()

# ================================================================ 一、项目概况与建设目标
d.h1("一、项目概况与建设目标")
d.h2("1.1 项目概况")
d.p("<一段话：甲方是谁（首次出现写全称并注明“以下简称“甲方””）、项目在哪、规模、业务构成。>")
d.image(FIG / "项目概况.png", 15.5, "项目概况")
d.table("项目基本情况", ["项目", "情况"], [
    ["<维度>", "<情况>"],
], [3.0, 13.0])

d.h2("1.2 主要问题与解决思路")
d.p("<一句话归纳问题，如：目前的问题集中在“数据缺、风险晚、人工多”三个方面，本方案逐一对应解决：>")
d.table("主要问题与解决思路", ["问题", "具体表现", "本方案怎么解决"], [
    ["<问题，≤ 6 字>", "<来自资料或会议的具体现象>", "<一句话对策，对应后文某一章>"],
], [2.8, 6.4, 6.8])

d.h2("1.3 建设目标")
d.table("建设目标", ["目标", "建成后能做到什么"], [
    ["<××看得见>", "<可检验的结果>"],
], [3.0, 13.0])

# ================================================================ 二、总体方案
d.h1("二、总体方案")
d.h2("2.1 总体框架")
d.p("本方案的主线是：**<一句话主线，如：四类硬件采集数据，一个数据底座统一口径，一个平台管理业务，六项 AI 功能辅助决策。>**"
    "总体框架自下而上分为 <N> 层：")
d.image(FIG / "总体框架.png", 15.5, "总体框架")
d.table("各层说明", ["层级", "包含内容", "作用", "详见"], [
    ["<层名>", "<模块>", "<作用>", "第<×>章"],
], [2.4, 6.4, 4.6, 2.6], center_cols=(3,))

d.h2("2.2 建设清单")
d.table("建设清单", ["类别", "内容", "数量", "说明"], [
    ("__group__", "硬件"),
    ["<设备>", "<型号与位置>", "<数量 / 按勘察确定>", "<已列入报价 / 需另行报价>"],
    ("__group__", "软件"),
    ["<系统>", "<功能>", "<数量>", "<说明>"],
    ("__group__", "服务"),
    ["<服务>", "<内容>", "—", "—"],
], [3.0, 7.0, 2.6, 3.4], center_cols=(2, 3))

d.mute = BOSS  # —— 汇报版不含建设原则 ——
d.h2("2.3 建设原则")
d.table("建设原则", ["原则", "说明"], [
    ["<原则>", "<说明>"],
], [3.0, 13.0])
d.mute = False

# ================================================================ 三、硬件方案（无硬件则删除本章，后续章节顺延编号）
d.h1("三、硬件方案")
d.p("<一句话：硬件负责采集哪几类数据。>")
d.image(FIG / "硬件布置.png", 15.5, "硬件布置示意")
d.table("硬件总览", ["设备", "安装位置", "采集数据", "主要用途"], [
    ["<设备>", "<位置>", "<数据>", "<用途>"],
], [3.0, 3.8, 4.6, 4.6])
d.p("以下每类设备按统一格式说明：用途、工作方式、采集数据、安装条件、与系统对接、怎么检验、限制。")
d.h2("3.1 <设备名>")
d.p("<为什么需要这类设备，一两句。>")
d.table("<设备名>说明", ["项目", "说明"], [
    ["用途", "<>"], ["工作方式", "<>"], ["采集数据", "<只写设备实际能输出的数据>"],
    ["安装条件", "<供电、网络、位置、施工时间、审批>"], ["与系统对接", "<平台是否原生支持；不支持写清接入路径>"],
    ["怎么检验", "<可操作的检验方法；精度以厂商书面承诺为准>"], ["限制", "<做不到的、会失效的情况>"],
], KV)
